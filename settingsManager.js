/**
 * Log administrative or system audit event to ring buffer and MongoDB.
 */
async function logAudit(action, category, details, username = 'system') {
  const entry = {
    timestamp: new Date(),
    action,
    category,
    details: typeof details === 'string' ? details : JSON.stringify(details),
    username: username || 'system'
  };

  // Add to in-memory buffer
  logBuffer.unshift(entry);
  if (logBuffer.length > MAX_LOG_BUFFER) {
    logBuffer.pop();
  }

  // Persist to MongoDB if available
  try {
    const db = await connectDB().catch(() => null);
    if (db) {
      await db.collection('admin_audit_logs').insertOne({
        ...entry,
        createdAt: new Date()
      }).catch(() => null);
    }
  } catch (err) {
    // Silent fallback
  }

  console.log(`[Admin Audit] [${category.toUpperCase()}] ${action} by ${username}: ${entry.details}`);
}

/**
 * Initialize and load settings from database.
 */
async function initSettings() {
  const defaults = getDefaultSettings();
  try {
    const db = await connectDB().catch(() => null);
    if (db) {
      const saved = await db.collection('settings').findOne({ _id: 'app_config' });
      if (saved) {
        cachedSettings = {
          pacs: { ...defaults.pacs, ...(saved.pacs || {}) },
          storage: { ...defaults.storage, ...(saved.storage || {}) },
          whatsapp: { ...defaults.whatsapp, ...(saved.whatsapp || {}) },
          reportTemplate: { ...defaults.reportTemplate, ...(saved.reportTemplate || {}) }
        };
        console.log('[SettingsManager] Loaded persistent application settings from MongoDB.');
        return cachedSettings;
      }
    }
  } catch (err) {
    console.warn('[SettingsManager] Failed to load settings from DB:', err.message);
  }

  cachedSettings = defaults;
  return cachedSettings;
}

/**
 * Get current system settings (with memory caching).
 */
async function getSettings() {
  if (!cachedSettings) {
    await initSettings();
  }
  return cachedSettings;
}

/**
 * Synchronous getter for in-memory settings.
 */
function getSettingsSync() {
  return cachedSettings || getDefaultSettings();
}

