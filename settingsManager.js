async function getRecentAuditLogs(limit = 50) {
  try {
    const db = await connectDB().catch(() => null);
    if (db) {
      const logs = await db.collection('admin_audit_logs')
        .find({})
        .sort({ timestamp: -1 })
        .limit(limit)
        .toArray();
      if (logs && logs.length > 0) {
        return logs;
      }
    }
  } catch (e) {}

  return logBuffer.slice(0, limit);
}

/**
 * Comprehensive System Health & Diagnostics Aggregator.
 */
async function getSystemDiagnostics(extraContext = {}) {
  const settings = getSettingsSync();
  const startTime = Date.now();

  // 1. PACS Host Connectivity Ping
  let pacsStatus = {
    online: false,
    pingMs: 0,
    responseTimeMs: 0,
    host: settings.pacs.pacsHost,
    httpStatus: null,
    error: null
  };
  try {
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 3500);
    const pStart = Date.now();
    const res = await fetch(`${settings.pacs.pacsHost}/api_session_keepalive.asp`, { signal: controller.signal });
    clearTimeout(timeout);
    const elapsed = Date.now() - pStart;
    pacsStatus.responseTimeMs = elapsed;
    pacsStatus.pingMs = elapsed;
    pacsStatus.httpStatus = res.status;
    pacsStatus.online = res.ok || res.status === 200 || res.status === 401; // Server responded
  } catch (pErr) {
    pacsStatus.error = pErr.message;
  }

  // 2. MongoDB Telemetry & Document Counts
  let mongoStatus = {
    online: false,
    connected: false,
    collections: {},
    totalStudies: 0,
    todayStudies: 0,
    pingMs: 0,
    error: null
  };
  try {
    const mStart = Date.now();
    const db = await connectDB().catch(() => null);
    if (db) {
      await db.command({ ping: 1 });
      mongoStatus.pingMs = Date.now() - mStart;
      mongoStatus.connected = true;
      mongoStatus.online = true;

      const todayStr = new Date().toISOString().split('T')[0];
      const [studiesCount, reportsCount, patientsCount, usersCount, todayCount] = await Promise.all([
        db.collection('studies').estimatedDocumentCount().catch(() => 0),
        db.collection('reports').estimatedDocumentCount().catch(() => 0),
        db.collection('patients').estimatedDocumentCount().catch(() => 0),
        db.collection('users').estimatedDocumentCount().catch(() => 0),
        db.collection('studies').countDocuments({ studyDate: todayStr }).catch(() => 0)
      ]);
      mongoStatus.totalStudies = studiesCount;
      mongoStatus.todayStudies = todayCount;
      mongoStatus.collections = {
        studies: studiesCount,
        reports: reportsCount,
        patients: patientsCount,
        users: usersCount
      };
    }
  } catch (mErr) {
    mongoStatus.error = mErr.message;
  }

  // 3. MinIO S3 Object Storage Status
  let minioStatus = {
    online: false,
    connected: false,
    endpoint: process.env.MINIO_ENDPOINT || 'pacs-minio',
    port: process.env.MINIO_PORT || 4010,
    bucket: process.env.MINIO_BUCKET || 'pacs-dicom',
    totalFiles: 0,
    totalDicomFiles: 0,
    totalBytes: 0,
    error: null
  };
  if (extraContext.minioStats) {
    minioStatus.connected = !extraContext.minioStats.error;
    minioStatus.online = minioStatus.connected;
    minioStatus.totalBytes = extraContext.minioStats.totalBytes || 0;
    minioStatus.totalFiles = extraContext.minioStats.totalDicomFiles || extraContext.minioStats.totalFiles || 0;
    minioStatus.totalDicomFiles = minioStatus.totalFiles;
    minioStatus.error = extraContext.minioStats.error || null;
  }

  // 4. WhatsApp / WATI Gateway Telemetry
  const whatsappStatus = {
    configured: !!((settings.whatsapp.watiAccessToken || settings.whatsapp.bearerToken) && (settings.whatsapp.apiEndpoint || settings.whatsapp.endpoint)),
    testMode: settings.whatsapp.testMode !== false,
    fixedTestPhone: settings.whatsapp.fixedTestPhone || '9498094815',
    templateName: settings.whatsapp.templateName || 'pacs_reports_new',
    autoRetry: settings.whatsapp.autoRetryEnabled !== false
  };

  // 5. Node.js & Host Runtime Telemetry
  const memoryUsage = process.memoryUsage();
  const uptimeSec = Math.floor(process.uptime());
  const runtime = {
    uptimeSeconds: uptimeSec,
    uptimeFormatted: formatUptime(uptimeSec),
    nodeVersion: process.version,
    platform: process.platform,
    arch: process.arch,
    pid: process.pid,
    rssMemoryMb: (memoryUsage.rss / (1024 * 1024)).toFixed(1),
    rssMb: (memoryUsage.rss / (1024 * 1024)).toFixed(1),
    heapUsedMb: (memoryUsage.heapUsed / (1024 * 1024)).toFixed(1),
    heapTotalMb: (memoryUsage.heapTotal / (1024 * 1024)).toFixed(1)
  };

  // 6. Storage Quota Calculations
  const maxCapGb = parseFloat(settings.storage?.maxCacheGb) || 100;
  const minioMb = (minioStatus.totalBytes || 0) / (1024 * 1024);
  const totalUsedMb = minioMb; // reports & thumbs if available
  const totalUsedGb = totalUsedMb / 1024;
  const utilPct = maxCapGb > 0 ? Math.round((totalUsedGb / maxCapGb) * 100) : 0;

  const storageStatus = {
    maxCapGb,
    totalUsedGb,
    utilizationPercent: utilPct,
    minioUsedMb: minioMb,
    reportsUsedMb: 0,
    thumbsUsedMb: 0
  };

  return {
    success: true,
    diagnosticsTimeMs: Date.now() - startTime,
    timestamp: new Date(),
    pacs: pacsStatus,
    mongo: mongoStatus,
    mongodb: mongoStatus,
    minio: minioStatus,
    whatsapp: whatsappStatus,
    system: runtime,
    runtime,
    storage: storageStatus,
    settings: {
      pacsHost: settings.pacs.pacsHost,
      maxCacheGb: settings.storage.maxCacheGb,
      hospitalName: settings.pacs.hospitalName
    }
  };
}

function formatUptime(seconds) {
  const d = Math.floor(seconds / (3600 * 24));
  const h = Math.floor((seconds % (3600 * 24)) / 3600);
  const m = Math.floor((seconds % 3600) / 60);
  const s = Math.floor(seconds % 60);
  if (d > 0) return `${d}d ${h}h ${m}m`;
  if (h > 0) return `${h}h ${m}m ${s}s`;
  return `${m}m ${s}s`;
}

